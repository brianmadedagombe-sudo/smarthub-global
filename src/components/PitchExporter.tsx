import { useState } from 'react';
import { FileDown, Loader2 } from 'lucide-react';
import type { AppApi } from '@/hooks/useApp';
import { Button } from '@/components/ui';
import { toast } from '@/components/Toast';
import { printDocument, buildPrintDocument } from '@/lib/print';
import { OWNER_NAME, OWNER_EMAIL, MPESA_PAYOUT_NUMBER } from '@/lib/config';

interface PitchExporterProps {
  api: AppApi;
}

export function PitchExporter({ api }: PitchExporterProps) {
  const [exporting, setExporting] = useState(false);

  const bio = api.state.bio;
  const services = api.state.services;
  const products = api.state.products.filter((p) => p.published);
  const sales = api.state.sales.filter((s) => s.status === 'success');
  const totalRevenue = sales.reduce((sum, s) => sum + s.amountKes, 0);

  const exportPdf = async () => {
    setExporting(true);
    try {
      const displayName = bio.displayName || OWNER_NAME;
      const tagline = bio.tagline || '';

      const serviceRows = services.length > 0
        ? services.map((s) => `<tr><td>${esc(s.name)}</td><td>${esc(s.trade)}</td><td>${esc(s.location)}</td><td class="right">${s.rating.toFixed(1)} ★</td></tr>`).join('')
        : '<tr><td colspan="4" class="muted" style="text-align:center;padding:16px">No services listed yet.</td></tr>';

      const productRows = products.length > 0
        ? products.map((p) => `<tr><td>${esc(p.title)}</td><td>${esc(p.category)}</td><td class="right">KES ${p.priceKes.toLocaleString()}</td></tr>`).join('')
        : '<tr><td colspan="3" class="muted" style="text-align:center;padding:16px">No products published yet.</td></tr>';

      const linkRows = bio.links.length > 0
        ? bio.links.map((l) => `<tr><td>${esc(l.label)}</td><td>${esc(l.kind)}</td><td>${esc(l.url)}</td>${l.price ? `<td class="right">${esc(l.price)}</td>` : '<td class="right">—</td>'}</tr>`).join('')
        : '<tr><td colspan="4" class="muted" style="text-align:center;padding:16px">No links added yet.</td></tr>';

      const body = `
        <h1>${esc(displayName)}</h1>
        <p class="subtitle">${esc(tagline)}</p>

        <div class="grid">
          <div class="card">
            <div class="label">Contact</div>
            <div style="margin-top:6px;font-size:13px">
              <div>${esc(OWNER_EMAIL)}</div>
              <div class="muted">${esc(MPESA_PAYOUT_NUMBER)}</div>
            </div>
          </div>
          <div class="card">
            <div class="label">Storefront Stats</div>
            <div class="value">${sales.length}</div>
            <div class="sub">Successful sales · KES ${totalRevenue.toLocaleString()} revenue</div>
          </div>
        </div>

        <h2>Services Offered</h2>
        <table>
          <thead><tr><th>Name</th><th>Trade</th><th>Location</th><th class="right">Rating</th></tr></thead>
          <tbody>${serviceRows}</tbody>
        </table>

        <h2>Digital Products</h2>
        <table>
          <thead><tr><th>Title</th><th>Category</th><th class="right">Price</th></tr></thead>
          <tbody>${productRows}</tbody>
        </table>

        <h2>Storefront Links</h2>
        <table>
          <thead><tr><th>Label</th><th>Type</th><th>URL</th><th class="right">Price</th></tr></thead>
          <tbody>${linkRows}</tbody>
        </table>

        <div class="footer" style="margin-top:32px;border-top:1px solid #e2e8f0;padding-top:12px">
          Generated by SmartHub Global · ${new Date().toLocaleDateString()}
        </div>
      `;

      const html = buildPrintDocument(`${displayName} — Business Pitch`, body);
      await printDocument({ html });
      toast('PDF summary ready — use your browser print dialog to save.');
    } catch {
      toast('Could not generate PDF. Please try again.', 'error');
    } finally {
      setExporting(false);
    }
  };

  return (
    <Button
      variant="secondary"
      fullWidth
      onClick={exportPdf}
      disabled={exporting}
      icon={exporting ? <Loader2 className="h-4 w-4 animate-spin" /> : <FileDown className="h-4 w-4" />}
    >
      {exporting ? 'Generating...' : 'Download PDF Summary'}
    </Button>
  );
}

function esc(s: string): string {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}
